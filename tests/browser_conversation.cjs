 assert.match(await panel.innerText(),/4 saved parent messages supplied as context/);
 const firstCard=panel.locator('.sentiment-items article').first();
 await panel.getByText('Why this label · inspect evidence',{exact:true}).first().click();
 await panel.getByText('Parent context used for this label',{exact:true}).first().click();
 assert.match(await panel.innerText(),/Separate message · not another sentiment vote/);
 assert.match(await panel.innerText(),/I think Microsoft pricing is fair/);
 await panel.getByText('Read the saved parent text',{exact:true}).first().click();
 assert.equal(await panel.getByRole('link',{name:'Open cited parent discussion ↗',exact:true}).first().getAttribute('href'),'https://news.ycombinator.com/item?id=999');
 await panel.getByRole('button',{name:'Original sources',exact:true}).click();
 await panel.getByRole('button',{name:'Inspect original source ↗',exact:true}).first().click();
 const modal=page.getByRole('dialog'),context=modal.getByRole('region',{name:'Original conversation context',exact:true});
 await context.getByText('Parent comment · separate message',{exact:true}).waitFor();
