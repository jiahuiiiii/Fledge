 assert.match(await context.innerText(),/I think Microsoft pricing is fair/);
 assert.match(await context.innerText(),/Loading it does not change a saved label/);
 assert.equal(await context.getByRole('button',{name:'Check original conversation again'}).isDisabled(),true);
 assert.equal(await context.getByRole('link',{name:'Open parent discussion ↗',exact:true}).getAttribute('href'),'https://news.ycombinator.com/item?id=999');
 assert.deepEqual(calls,[]);
 for(const width of [320,390,1440]){await page.setViewportSize({width,height:1000});assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));await page.screenshot({path:`/private/tmp/thesis-conversation-${width}.png`,fullPage:true});}
 // Frontend acquisition failure is mocked; collector transport is separately exercised in backend tests.
 await page.keyboard.press('Escape');
 let saved;
