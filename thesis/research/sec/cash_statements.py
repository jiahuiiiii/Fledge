"""Recognise cash-flow totals by their original statement rows, not issuer names.

A continuing-operations tag is not a blanket alias for all operations. Only an
explicit total row in the cash-flow statement can establish that mapping.
"""
from decimal import Decimal
from html.parser import HTMLParser
import re

OPERATING = 'NetCashProvidedByUsedInOperatingActivities'
CONTINUING = OPERATING + 'ContinuingOperations'
PPE = 'PaymentsToAcquirePropertyPlantAndEquipment'
PRODUCTIVE = 'PaymentsToAcquireProductiveAssets'


def words(text):
    return re.sub(r'[^a-z0-9 ]', ' ', text.lower()).replace('  ', ' ').strip()


def operating_total(label):
    return bool(re.fullmatch(r'(?:net )?cash (?:generated by|provided by|provided by used in|provided by or used in|used in|used in provided by|used in or provided by) operating activities', ' '.join(words(label).split())))


def capital_target(label):
    text = ' '.join(words(label).split())
    match = re.fullmatch(r'(?:payments for (?:the )?acquisition of|purchases of|purchases related to|cash purchases of|acquisitions of) property(?: plant)? and equipment( and (?:intangible assets|software|software and intangible assets))?', text)
    return (PRODUCTIVE if match[1] else PPE) if match else None


def statement_table(table):
    text = ' '.join(words(r['label']) for r in table['rows'])
    return (all(part in text for part in ('operating activities', 'investing activities', 'financing activities'))
            and any(operating_total(r['label']) for r in table['rows'])
            and any(words(r['label']).startswith(('net income', 'net loss', 'net earnings')) for r in table['rows']))


def discontinued(bundle, filing, start, end):
    """Do not relabel a continuing figure when discontinued flows are reported."""
    for tag, item in bundle['companyfacts'].get('facts', {}).get('us-gaap', {}).items():
        if 'Discontinued' not in tag or not any(s in tag for s in ('Cash', 'IncomeLoss')): continue
        for values in item.get('units', {}).values():
            for f in values:
                if (f.get('accn'), f.get('start'), f.get('end')) == (filing['accessionNumber'], start, end):
                    try:
                        if Decimal(str(f.get('val'))) != 0: return True
                    except (ValueError, ArithmeticError): return True
    return False


def tagged_recoveries(parsed, bundle, filing):
    result = []
    for table in parsed['tables']:
        if not statement_table(table): continue
        # A separated cash-flow subtotal is not the whole-company total.
        if any('discontinued' in words(r['label']) for r in table['rows']): continue
        for row in table['rows']:
            capital = capital_target(row['label'])
            for f in row['facts']:
                if f['dimensions'] or f['reason'] or f['value'] is None or f['unit'] != 'USD' or not f['start']: continue
                target = None
                if operating_total(row['label']) and f['concept'].split(':')[-1] == CONTINUING and f['standard']:
                    if not discontinued(bundle, filing, f['start'], f['end']): target = OPERATING
                elif capital and not f['standard'] and Decimal(f['value']) >= 0:
                    # Purchases in the investing section; not principal payments
                    # or noncash additions disclosed beneath the statement.
                    index = table['rows'].index(row)
                    preceding = ' '.join(words(r['label']) for r in table['rows'][:index])
                    if 'investing activities' in preceding and 'financing activities' not in preceding: target = capital
                if target:
                    result.append(dict(target=target, value=f['value'], start=f['start'], end=f['end'], inputs=[f], formula=None,
                        explanation='The original cash-flow statement explicitly labels this amount as '+('total operating cash flow.' if target == OPERATING else 'cash purchases of property and equipment'+(' and intangible assets.' if target == PRODUCTIVE else '.'))))
    return result


class Tables(HTMLParser):
    """Visible row/cell boundaries for pre-inline filings; never parse amounts."""
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.tables=[];self.frames=[];self.stack=[];self.hidden=0;self.text='';self.count=0

    def handle_starttag(self, tag, attrs):
        attrs=dict(attrs);hidden=tag in ('script','style','noscript','ix:hidden','ix:header') or 'hidden' in attrs or bool(re.search(r'display\s*:\s*none|visibility\s*:\s*hidden',attrs.get('style',''),re.I))
        if tag not in ('br','hr','meta','link','img','input','wbr','source','area','base','embed','param','col'):
            self.stack.append((tag,hidden));self.hidden+=hidden
        if self.hidden:return
        if tag=='table':self.frames.append(dict(rows=[],before=self.text[-1500:],cells=None,cell=None))
        if not self.frames:return
        frame=self.frames[-1]
        if tag=='tr':frame['cells']=[];frame['cell']=None
        if tag in ('td','th') and frame['cells'] is not None:
            frame['cells'].append([]);frame['cell']=frame['cells'][-1]

    def handle_data(self, text):
        self.count+=len(text)
        if self.count>20_000_000:raise ValueError('Cash-flow table text exceeds limit.')
        if self.hidden:return
        self.text=(self.text+' '+text)[-3000:]
        if self.frames and self.frames[-1]['cell'] is not None:self.frames[-1]['cell'].append(text)

    def handle_endtag(self, tag):
        if not self.hidden and self.frames:
            frame=self.frames[-1]
            if tag in ('td','th'):frame['cell']=None
            if tag=='tr' and frame['cells'] is not None:
                cells=[' '.join(''.join(c).split()) for c in frame['cells']]
                nonempty=[c for c in cells if c]
                frame['rows'].append(dict(label=nonempty[0] if nonempty else '',cells=cells));frame['cells']=None;frame['cell']=None
            if tag=='table':
                if len(frame['rows'])<=600:self.tables.append(frame)
                self.frames.pop()
        match=next((i for i in range(len(self.stack)-1,-1,-1) if self.stack[i][0]==tag),None)
        if match is not None:
            self.hidden-=sum(h for _,h in self.stack[match:]);del self.stack[match:]


def legacy_recoveries(raw, bundle, filing):
    """Confirm existing structured amounts against an explicit untagged total.

    Values/dates come from the exact filing's SEC fact, not positional HTML
    guesses. The printed scale, amount, year and total-row label must match.
    """
    from .performance import collect
    facts=collect(bundle,filing,(CONTINUING,))
    if not facts:return []
    reader=Tables();reader.feed(raw.decode('utf-8-sig'));reader.close();result=[]
    for ti,table in enumerate(reader.tables):
        if not statement_table(table):continue
        table_text=' '.join(' '.join(r['cells']) for r in table['rows'])
        if 'discontinued' in words(table_text):continue
        scale_text=(table['before']+' '+table_text[:500]).lower()
        scales={name for name in ('millions','thousands') if re.search(r'\bin '+name+r'\b',scale_text)}
        if len(scales)!=1:continue
        scale=Decimal(1_000_000 if 'millions' in scales else 1000)
        for row in table['rows']:
            if not operating_total(row['label']):continue
            # Separate currency and parentheses cells are common in old HTML.
            printed=' '.join(row['cells'][row['cells'].index(row['label'])+1:]).replace('$','').replace('\u2212','-')
            numbers=re.findall(r'\(?\s*-?\d[\d,]*(?:\.\d+)?\s*\)?',printed)
            values=[]
            for n in numbers:
                negative='(' in n or '-' in n
                value=Decimal(re.sub(r'[^0-9.]','',n))*scale
                values.append(-value if negative else value)
            for f in facts:
                if f['start'] is None or f['end']>filing['end'].isoformat() or f['end'][:4] not in table_text:continue
                if Decimal(f['value']) not in values or discontinued(bundle,filing,f['start'],f['end']):continue
                original=dict(f,row_label=row['label'],row_text=' | '.join(row['cells']),table_id=f'legacy-cash-table-{ti}')
                result.append(dict(target=OPERATING,value=f['value'],start=f['start'],end=f['end'],inputs=[original],formula=None,
                    explanation='The original cash-flow statement identifies the existing SEC-tagged amount as total operating cash flow; its printed amount and scale match.'))
    return result
